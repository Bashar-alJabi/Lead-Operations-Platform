import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';

test('Manager reserves and binds a sender while the Agent sees prepared, accepted and ambiguous internal alerts',async({page,browser})=>{
 await page.setExtraHTTPHeaders({'x-e2e-rate-scope':randomUUID()});
 const {password,testToken}=JSON.parse(await readFile('.local/e2e/fixture.json','utf8')) as {password:string;testToken:string};
 await page.goto('/');
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('en');
 await page.getByLabel('Email',{exact:true}).fill('manager@browser.test');
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('button',{name:'Messaging setup',exact:true}).click();
 await page.getByRole('row').filter({hasText:'Browser Staff Connection'}).getByRole('button').click();
 const row=page.getByRole('listitem').filter({hasText:'Browser Staff Sender'});
 await row.getByRole('button',{name:'Reserve for internal notifications',exact:true}).click();
 await row.getByLabel('Sender reservation reason',{exact:true}).fill('Reserve a synthetic staff-only sender');
 await row.getByRole('button',{name:'Confirm sender reservation',exact:true}).click();
 await expect(row).toContainText('Internal sender only');
 await expect(row.getByRole('button',{name:'Enable sender',exact:true})).toHaveCount(0);
 const defaults=page.getByRole('heading',{name:'Branch default sender',exact:true}).locator('..');
 await expect(defaults.getByRole('option').filter({hasText:'Browser Staff Sender'})).toHaveCount(0);
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('fr');
 await expect(row).toContainText('Expéditeur interne uniquement');
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('en');
 await page.getByRole('button',{name:'Notifications',exact:true}).click();
 await page.getByText('Internal messaging notifications',{exact:true}).click();
 const binding=page.locator('[data-staff-messaging-binding]');
 await binding.getByLabel('Approved sender and template',{exact:true}).selectOption({label:'Browser Staff Sender · browser_staff_notice (en_US)'});
 await expect(binding).toContainText('<img src=x> You have a staff alert in the platform.');
 await expect(binding.locator('img')).toHaveCount(0);
 await binding.getByLabel('Enable event',{exact:true}).check();
 await binding.getByLabel('Internal template change reason',{exact:true}).fill('Approve synthetic staff wording');
 await binding.getByRole('button',{name:'Save internal messaging binding',exact:true}).click();
 await expect(binding.getByLabel('Internal template change reason',{exact:true})).toHaveValue('');
 await binding.getByRole('button',{name:'History',exact:true}).click();
 await expect(binding).toContainText('Approve synthetic staff wording');
 const preferences=page.locator('[data-staff-messaging-preference]');
 await expect(preferences.getByLabel('Enable event',{exact:true})).toBeDisabled();
 const context=await browser.newContext({extraHTTPHeaders:{'x-e2e-rate-scope':randomUUID()}});
 try {
  const staff=await context.newPage();await staff.goto('/');
  await staff.getByRole('combobox',{name:'Language',exact:true}).selectOption('en');
  await staff.getByLabel('Email',{exact:true}).fill('agent@browser.test');
  await staff.getByLabel('Password',{exact:true}).fill(password);
  await staff.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(staff.getByRole('button',{name:'Sign out',exact:true})).toBeVisible();
  const actor=await(await staff.request.get('/api/auth/me')).json();
  const headers={origin:'http://127.0.0.1:4100'},phone='+15550074302';
  const base='/api/notification-messaging';
  expect((await page.request.put(`/api/users/${actor.id}/notification-messaging-destination`,{headers,data:{version:0,phone}})).status()).toBe(200);
  expect((await staff.request.put(base+'/destination',{headers,data:{version:1,phone,enabled:true}})).status()).toBe(200);
  expect((await staff.request.put(base+'/preferences/LEAD_ASSIGNED',{headers,data:{version:0,language:'en',enabled:true}})).status()).toBe(200);
  const create=await page.request.post('/api/campaigns',{headers,data:{branchId:actor.branchId,name:'Staff messaging test campaign',routingMethod:'MANUAL'}});
  expect(create.status()).toBe(201);
  const {id:campaignId}=await create.json();
  expect((await page.request.post(`/api/campaigns/${campaignId}/activate`,{headers})).status()).toBe(200);
  const lead=await page.request.post('/api/leads',{headers,data:{branchId:actor.branchId,campaignId,contact:{name:'Staff test lead',phone:'+15550074303'}}});
  expect(lead.status()).toBe(201);
  const {id:leadId}=await lead.json();
  expect((await page.request.post(`/api/leads/${leadId}/assignment`,{headers,data:{version:1,agentId:actor.id,reason:'Trigger a synthetic staff alert'}})).status()).toBe(200);
  const control={...headers,authorization:'Bearer '+testToken};
  const interrupted=await page.request.post('/__test__/staff-messaging-publication-failure',{headers:control,data:{leadId}});
  expect(interrupted.status(),await interrupted.text()).toBe(200);
  const {id:publicationId}=await interrupted.json();
  const recovery=page.locator('[data-staff-messaging-recovery]');
  const publication=recovery.locator(`[data-staff-messaging-publication="${publicationId}"]`);
  await recovery.getByRole('button',{name:'Load failed preparations',exact:true}).click();
  await expect(publication).toContainText('Preparation stopped');
  await expect(publication).not.toContainText('Staff test lead');
  await expect(publication).not.toContainText(phone);
  const recoveryPath=`${base}/branches/${actor.branchId}/publications/en/${publicationId}`;
  expect((await staff.request.post(recoveryPath+'/recover',{headers,data:{version:0,reason:'Synthetic agent denial'}})).status()).toBe(403);
  await publication.getByLabel('Preparation recovery reason',{exact:true}).fill('Fixed synthetic preparation failure');
  await publication.getByRole('button',{name:'Resume preparation',exact:true}).click();
  await expect(publication).toContainText('Waiting to prepare audience');
  await publication.getByRole('button',{name:'History',exact:true}).click();
  await expect(publication).toContainText('Fixed synthetic preparation failure');
  const prepared=await page.request.post('/__test__/staff-messaging-publication',{
   headers:control,
  });
  expect(prepared.status(),await prepared.text()).toBe(200);
  await staff.getByRole('button',{name:'Notifications',exact:true}).click();
  await staff.getByText('Internal messaging notifications',{exact:true}).click();
  const activity=staff.locator('[data-staff-messaging-activity]');
  await activity.getByRole('button',{name:'Reload settings',exact:true}).click();
  await expect(activity).toContainText('Prepared');
  await expect(activity).not.toContainText(phone);
  await recovery.getByRole('button',{name:'Load failed preparations',exact:true}).click();
  await expect(publication).toContainText('Preparation complete');
  await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('fr');
  await expect(publication).toContainText('Préparation terminée');
  await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('en');
  const dispatch=async(result:'ACK'|'UNKNOWN')=>{
   const response=await page.request.post('/__test__/staff-messaging-dispatch',{headers:control,data:{result}});
   expect(response.status(),await response.text()).toBe(200);
   return response.json();
  };
  expect(await dispatch('ACK')).toEqual({worked:true,calls:1});
  await activity.getByRole('button',{name:'Reload settings',exact:true}).click();
  await expect(activity).toContainText('Accepted by provider');
  await activity.getByRole('button',{name:'Dispatch history',exact:true}).click();
  await expect(activity).toContainText('Sending');
  await expect(activity).not.toContainText('wamid.browser-staff-dispatch');
  async function prepareAnother(customerPhone:string){
   const lead=await page.request.post('/api/leads',{headers,data:{branchId:actor.branchId,campaignId,
    contact:{name:'Synthetic internal notification lead',phone:customerPhone}}});
   expect(lead.status()).toBe(201);
   const {id}=await lead.json();
   expect((await page.request.post(`/api/leads/${id}/assignment`,{headers,data:{version:1,agentId:actor.id,reason:'New staff notification'}})).status()).toBe(200);
   expect((await page.request.post('/__test__/staff-messaging-publication',{headers:control})).status()).toBe(200);
  }
  await prepareAnother('+15550074304');
  expect(await dispatch('UNKNOWN')).toEqual({worked:true,calls:1});
  expect(await dispatch('ACK')).toEqual({worked:false,calls:0});
  await activity.getByRole('button',{name:'Reload settings',exact:true}).click();
  await expect(activity).toContainText('Outcome unknown');
  await prepareAnother('+15550074305');
  expect((await staff.request.put(base+'/destination',{headers,data:{version:2,phone:null,enabled:false}})).status()).toBe(200);
  expect(await dispatch('ACK')).toEqual({worked:true,calls:0});
  await activity.getByRole('button',{name:'Reload settings',exact:true}).click();
  await expect(activity).toContainText('Suppressed after a change');
 } finally {await context.close();}
});
